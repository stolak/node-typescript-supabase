const lines = rawData.split('\n').filter(line => line.trim());
const items = [];

lines.forEach((line, index) => {
  const trimmed = line.trim();
  if (!trimmed) return;
  
  // Try to extract quantity (last number in the line)
  const qtyMatch = trimmed.match(/\s+(\d+)\s*$/);
  let name = trimmed;
  let qty = 0;
  
  if (qtyMatch) {
    qty = parseInt(qtyMatch[1], 10);
    name = trimmed.substring(0, qtyMatch.index).trim();
  } else {
    // Try to find any number at the end
    const lastNumMatch = trimmed.match(/(\d+)$/);
    if (lastNumMatch && lastNumMatch.index > trimmed.length - 10) {
      qty = parseInt(lastNumMatch[1], 10);
      name = trimmed.substring(0, lastNumMatch.index).trim();
    }
  }
  
  // Generate SKU from index
  const sku = `ITEM-${String(index + 1).padStart(4, '0')}`;
  
  items.push({
    sku,
    name,
    qty: qty || 0
  });
});

